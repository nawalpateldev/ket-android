package com.ketgrouponline.Bean;

public class ContactBean {
    private String id,
            mobile,
            email,
            name,
            about_details,
            youtube,
            facebook,
            twitter,
            instagram,
            youtube_help_video;

    public ContactBean() {
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getMobile() {
        return mobile;
    }

    public void setMobile(String mobile) {
        this.mobile = mobile;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getAbout_details() {
        return about_details;
    }

    public void setAbout_details(String about_details) {
        this.about_details = about_details;
    }

    public String getYoutube() {
        return youtube;
    }

    public void setYoutube(String youtube) {
        this.youtube = youtube;
    }

    public String getFacebook() {
        return facebook;
    }

    public void setFacebook(String facebook) {
        this.facebook = facebook;
    }

    public String getTwitter() {
        return twitter;
    }

    public void setTwitter(String twitter) {
        this.twitter = twitter;
    }

    public String getInstagram() {
        return instagram;
    }

    public void setInstagram(String instagram) {
        this.instagram = instagram;
    }

    public String getYoutube_help_video() {
        return youtube_help_video;
    }

    public void setYoutube_help_video(String youtube_help_video) {
        this.youtube_help_video = youtube_help_video;
    }
}
