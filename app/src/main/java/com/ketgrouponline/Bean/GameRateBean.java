package com.ketgrouponline.Bean;

public class GameRateBean {
    private String id,
            single_multiplier,
            jodi_multiplier,
            single_pana_multiplier,
            double_pana_multiplier,
            triple_pana_multiplier,
            time;

    public GameRateBean() {
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getSingle_multiplier() {
        return single_multiplier;
    }

    public void setSingle_multiplier(String single_multiplier) {
        this.single_multiplier = single_multiplier;
    }

    public String getJodi_multiplier() {
        return jodi_multiplier;
    }

    public void setJodi_multiplier(String jodi_multiplier) {
        this.jodi_multiplier = jodi_multiplier;
    }

    public String getSingle_pana_multiplier() {
        return single_pana_multiplier;
    }

    public void setSingle_pana_multiplier(String single_pana_multiplier) {
        this.single_pana_multiplier = single_pana_multiplier;
    }

    public String getDouble_pana_multiplier() {
        return double_pana_multiplier;
    }

    public void setDouble_pana_multiplier(String double_pana_multiplier) {
        this.double_pana_multiplier = double_pana_multiplier;
    }

    public String getTriple_pana_multiplier() {
        return triple_pana_multiplier;
    }

    public void setTriple_pana_multiplier(String triple_pana_multiplier) {
        this.triple_pana_multiplier = triple_pana_multiplier;
    }

    public String getTime() {
        return time;
    }

    public void setTime(String time) {
        this.time = time;
    }
}
